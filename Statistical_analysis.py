def compute_area_changes(gdf_22, gdf_24):
    """
    Compute total land-use area in 2022 and 2024 and determine the dominant transitions.
    """
    undeveloped_use = ["SIN_EDIF"]
    developed_use = ['RES_UNI', 'RE_PLU', 'COM_OFI', 'IND', 'OTROS']
    
    d_uses_area = {'Undeveloped_22': 0,
                   'Undeveloped_24': 0,
                   'Developed_22': 0,
                   'Developed_24': 0
                   }

    d_uses_area['Undeveloped_22'] = gdf_22[gdf_22["USO"].isin(undeveloped_use)]["AREA"].sum()
    d_uses_area['Undeveloped_24'] = gdf_24[gdf_24["USO"].isin(undeveloped_use)]["AREA"].sum()

    d_uses_area['Developed_22'] = gdf_22[gdf_22["USO"].isin(developed_use)]["AREA"].sum()
    d_uses_area['Developed_24'] = gdf_24[gdf_24["USO"].isin(developed_use)]["AREA"].sum()
    
    # Compute total area in each year
    d_uses_area["Total_22"] = d_uses_area['Developed_22'] + d_uses_area['Undeveloped_22']
    d_uses_area["Total_24"] = d_uses_area['Developed_24'] + d_uses_area['Undeveloped_24']

    # Compute proportion of developed land
    d_uses_area['Developed_Proportion_22'] = d_uses_area['Developed_22'] / d_uses_area["Total_22"] if d_uses_area["Total_22"] > 0 else 0
    d_uses_area['Developed_Proportion_24'] = d_uses_area['Developed_24'] / d_uses_area["Total_24"] if d_uses_area["Total_24"] > 0 else 0
    
    d_uses_area['Undeveloped_Proportion_22'] = d_uses_area['Undeveloped_22'] / d_uses_area["Total_22"] if d_uses_area["Total_22"] > 0 else 0
    d_uses_area['Undeveloped_Proportion_24'] = d_uses_area['Undeveloped_24'] / d_uses_area["Total_24"] if d_uses_area["Total_24"] > 0 else 0

    change_label = None

    # **Categorization of Change**

    if (d_uses_area['Developed_Proportion_24'] > d_uses_area['Developed_Proportion_22']):
        # If the proportion of developed land increased → **Growth**
            change_label = "↑"

    elif d_uses_area['Developed_Proportion_24'] < d_uses_area['Developed_Proportion_22']:
        if (d_uses_area['Developed_24'] > d_uses_area['Developed_22']):
            change_label = "↑"
        else:
            # If the proportion of developed land decreased → **Decline**
            change_label = "↓"
    else:
        # If proportions remained the same → **Stable**
        change_label = "="
    
    d_uses_area['Change_Label'] = change_label

    return d_uses_area
