# Define exact thresholds for coloring based on previous labeling rules
def get_effect_color(dunn_p, delta):
    """
    Assigns colors based on the effect size and Dunn’s test result.
    - "=" (Similar) with dunn_p < 0.05 → Gray
    - "=" (Similar) with dunn_p ≥ 0.05 → Light Orange
    - "↑" (Moderate Increase) → Light Green
    - "↓" (Moderate Decrease) → Light Blue
    - "↑↑" (Large Increase) → Dark Green
    - "↓↓" (Large Decrease) → Dark Blue
    """
    if dunn_p >= 0.05:  # No significant difference by Dunn’s test
        return "#f1e998" if abs(delta) <= 0.15 else "white"
    elif abs(delta) <= 0.15:
        return "gray"  # Negligible effect but statistically significant
    elif 0.15 < abs(delta) < 0.5:
        return "lightgreen" if delta > 0 else "lightblue"  # Moderate effect
    elif abs(delta) >= 0.5:
        return "green" if delta > 0 else "blue"  # Large effect
    else:
        return "white"

