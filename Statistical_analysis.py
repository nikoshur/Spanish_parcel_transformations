def standard_cv(series):
    """Compute standard CV = (std / mean) * 100."""
    series = series.dropna()
    if len(series) < 2:
        return 0.0
    mean_val = series.mean()
    std_val = series.std()
    return (std_val / mean_val) * 100 if mean_val != 0 else 0.0
# -------------------------------
def robust_cv(series):
    """Compute robust CV = (IQR / median) * 100."""
    series = series.dropna()
    if len(series) == 0:
        return 0.0
    median_val = series.median()
    q75, q25 = series.quantile(0.75), series.quantile(0.25)
    iqr_val = q75 - q25
    return (iqr_val / median_val) * 100 if median_val != 0 else 0.0
