def assign_ratio_label(ratio):
    """Assign labels based on ratio values."""
    if ratio is None:
        return None
    if ratio < 0.5:
        return "↓↓"  # Severe decrease
    elif 0.5 <= ratio < 0.9:
        return "↓"  # Moderate decrease
    elif 0.9 <= ratio <= 1.1:
        return "="
    elif 1.1 < ratio <= 1.5:
        return "↑"  # Moderate increase
    else:
        return "↑↑"  # Severe increase
