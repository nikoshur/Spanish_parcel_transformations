# Calculate area-weighted percentages for each category
def calculate_area_weighted_percentages(df, group_by_col):
    total_area = df['AREA'].sum()
    area_weighted_percentages = df.groupby(group_by_col)['AREA'].sum() / total_area * 100
    return area_weighted_percentages, total_area

