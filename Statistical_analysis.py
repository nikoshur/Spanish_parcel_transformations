def categorize_use_change(uses_22, uses_24):                                                             
    # Check if change happens exclusively from SIN_EDIF to others
    if len(set(uses_22)) < len(set(uses_24)):
        
        if ("SIN_EDIF" in set(uses_24)) and not ("SIN_EDIF" in set(uses_22)):
            return "Same_uses_but_extra_Undeveloped"
        else:
            return "Diversification"
    
    elif len(set(uses_22)) == len(set(uses_24)):
        
        if set(uses_22) == set(uses_24):  # No land-use change
            return "Same_uses"
        
        if set(uses_22) == {"SIN_EDIF"} and set(uses_24) == {"SIN_EDIF"}:  # No land-use change
            return "Undeveloped"
        
        else:
            return "Reclassification"
        
    elif len(set(uses_22)) > len(set(uses_24)):
        
        if ("SIN_EDIF" in set(uses_22)) and not ("SIN_EDIF" in set(uses_24)):
            return "Consolidation"
        else:        
            return "Reduction"
    
