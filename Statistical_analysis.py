def iqr_filtered_mean(series):
    """Compute the mean after removing outliers using the IQR method."""
    series = series.dropna()
    q25, q75 = np.percentile(series, [25, 75])
    iqr = q75 - q25
    lower_bound = q25 - 1.5 * iqr
    upper_bound = q75 + 1.5 * iqr
    filtered_series = series[(series >= lower_bound) & (series <= upper_bound)]
    return filtered_series.mean() if not filtered_series.empty else np.nan
