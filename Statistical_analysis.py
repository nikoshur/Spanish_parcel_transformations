def compute_stats_by_year(df, metrics):
    """
    Computes summary statistics (mean, median, std) for each metric,
    separately for the years 2022 and 2024, and calculates the difference
    between 2024 and 2022 for the mean and median.
    
    Parameters:
      df (pd.DataFrame): The input DataFrame containing a 'YEAR' column.
      metrics (list): List of metric column names.
      
    Returns:
      pd.DataFrame: A DataFrame with the computed statistics.
    """
    stats = []
    for metric in metrics:
        # Filter data for each year (assumes 'YEAR' is a column in df)
        data_2022 = df[df['YEAR'] == 2022][metric].dropna()
        data_2024 = df[df['YEAR'] == 2024][metric].dropna()
        
        # Compute statistics for 2022
        mean_2022 = data_2022.mean()
        median_2022 = data_2022.median()
        std_2022 = data_2022.std()
        
        # Compute statistics for 2024
        mean_2024 = data_2024.mean()
        median_2024 = data_2024.median()
        std_2024 = data_2024.std()
        
        # Differences (2024 - 2022)
        diff_mean = mean_2024 - mean_2022
        diff_median = median_2024 - median_2022
        
        stats.append({
            'metric': metric,
            'mean_2022': mean_2022,
            'median_2022': median_2022,
            'std_2022': std_2022,
            'mean_2024': mean_2024,
            'median_2024': median_2024,
            'std_2024': std_2024,
            'diff_mean': diff_mean,
            'diff_median': diff_median
        })
    return pd.DataFrame(stats)

