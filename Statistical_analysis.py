def assign_dispersion_label(n_parcels, cv_std, cv_robust, min_parcels_robust=10):
    """Assign dispersion labels based on CV values."""
    if n_parcels is None or n_parcels == 0:
        return None
    # Use standard CV if parcel count < min_parcels_robust, else use robust CV
    cv = cv_std if n_parcels < min_parcels_robust else cv_robust
    if cv <= 25:
        return "Uniform"
    elif cv <= 100:
        return "Moderate_Dispersion"
    else:
        return "High_Dispersion"
